"""Eval-table plugin and offline guard.

Scenario tests are marked `@pytest.mark.eval(id, title, expected)` and take the `ev` fixture, filling
in `ev.actual` and `ev.notes` from what they observed. After a full run (all scenarios collected),
the table is written to evals/results.md and evals/results.csv.
"""
from __future__ import annotations

import csv
import socket
from dataclasses import dataclass, field
from pathlib import Path

import pytest

EVALS_DIR = Path(__file__).resolve().parent.parent / "evals"
_records: list["EvalRecord"] = []


@dataclass
class EvalRecord:
    id: str
    title: str
    expected: str
    category: str = "must"
    actual: str = ""
    notes: list[str] = field(default_factory=list)
    passed: bool | None = None

    def note(self, text: str) -> None:
        self.notes.append(text)


def pytest_configure(config):
    config.addinivalue_line("markers", "eval(id, title, expected, category='must'): an eval-table scenario")


@pytest.fixture
def ev(request) -> EvalRecord:
    m = request.node.get_closest_marker("eval")
    assert m is not None, "the ev fixture needs @pytest.mark.eval(...)"
    rec = EvalRecord(**m.kwargs)
    request.node._eval = rec
    _records.append(rec)
    return rec


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    report = (yield).get_result()
    rec = getattr(item, "_eval", None)
    if rec is None or report.when != "call":
        return
    rec.passed = report.passed
    if report.failed:
        msg = str(call.excinfo.value).strip().splitlines()
        rec.note("FAILED: " + (msg[0][:200] if msg else call.excinfo.typename))


def _order(rec: EvalRecord):
    head = rec.id.split("/")[0].rstrip("ab")
    return (rec.category != "must", int(head) if head.isdigit() else 999, rec.id)


def pytest_sessionfinish(session, exitstatus):
    expected = sum(1 for item in session.items if item.get_closest_marker("eval"))
    if not _records or len(_records) < expected or session.config.option.keyword:
        return  # partial run: keep the last full table
    rows = sorted(_records, key=_order)
    EVALS_DIR.mkdir(exist_ok=True)
    passed = sum(1 for r in rows if r.passed)
    lines = ["# Eval results", "",
             f"Generated by `make eval` (offline: scripted models, mock provider, frozen clock). "
             f"**{passed}/{len(rows)} passed.** Every scenario also checks invariants I1–I7 "
             "(see `tests/invariants.py`).", "",
             "| # | Scenario | Expected | Actual | Result | Notes |", "|---|---|---|---|---|---|"]
    cell = lambda s: s.replace("|", "\\|").replace("\n", " ")
    for r in rows:
        tag = "" if r.category == "must" else " *(stretch)*"
        lines.append(f"| {r.id} | {cell(r.title)}{tag} | {cell(r.expected)} | {cell(r.actual or '—')} | "
                     f"{'✅ pass' if r.passed else '❌ fail'} | {cell('; '.join(r.notes))} |")
    (EVALS_DIR / "results.md").write_text("\n".join(lines) + "\n")
    with (EVALS_DIR / "results.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "category", "scenario", "expected", "actual", "result", "notes"])
        for r in rows:
            w.writerow([r.id, r.category, r.title, r.expected, r.actual, "pass" if r.passed else "fail",
                        "; ".join(r.notes)])


# ---------- offline guard: evals must never reach a network LLM ----------
_real_connect = socket.socket.connect


def _guarded_connect(self, address):
    if self.family == getattr(socket, "AF_UNIX", None):
        return _real_connect(self, address)
    raise RuntimeError(f"network access during tests is not allowed (tried {address!r})")


@pytest.fixture(autouse=True)
def no_network(monkeypatch):
    monkeypatch.setattr(socket.socket, "connect", _guarded_connect)
